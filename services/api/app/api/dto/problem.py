"""RFC 7807 Problem Details representation and API Exceptions."""

from typing import Optional, Dict, Any, List
from pydantic import BaseModel, Field


class ProblemDetails(BaseModel):
    type: str = Field(default="about:blank", description="URI reference identifying the problem type")
    title: str = Field(description="Short, human-readable summary of the problem type")
    status: int = Field(description="The HTTP status code generated by the origin server")
    detail: Optional[str] = Field(default=None, description="Human-readable explanation specific to this occurrence")
    instance: Optional[str] = Field(default=None, description="URI reference identifying the specific occurrence")
    invalid_params: Optional[List[Dict[str, Any]]] = Field(default=None, description="Validation errors if applicable")


class ApiException(Exception):
    def __init__(
        self,
        status: int,
        title: str,
        detail: Optional[str] = None,
        type_uri: Optional[str] = None,
        instance: Optional[str] = None,
        invalid_params: Optional[List[Dict[str, Any]]] = None,
        headers: Optional[Dict[str, str]] = None,
    ):
        self.status = status
        self.title = title
        self.detail = detail
        self.type_uri = type_uri or f"https://api.evc.io/errors/{status}"
        self.instance = instance
        self.invalid_params = invalid_params
        self.headers = headers or {}
        super().__init__(detail or title)

    def to_problem_details(self) -> ProblemDetails:
        return ProblemDetails(
            type=self.type_uri,
            title=self.title,
            status=self.status,
            detail=self.detail,
            instance=self.instance,
            invalid_params=self.invalid_params,
        )


class NotFoundException(ApiException):
    def __init__(self, detail: str = "Resource not found", instance: Optional[str] = None):
        super().__init__(status=404, title="Not Found", detail=detail, instance=instance)


class UnauthorizedException(ApiException):
    def __init__(self, detail: str = "Authentication required", instance: Optional[str] = None):
        super().__init__(
            status=401,
            title="Unauthorized",
            detail=detail,
            instance=instance,
            headers={"WWW-Authenticate": "Bearer"},
        )


class ForbiddenException(ApiException):
    def __init__(self, detail: str = "Insufficient permissions or tenant mismatch", instance: Optional[str] = None):
        super().__init__(status=403, title="Forbidden", detail=detail, instance=instance)


class RateLimitExceededException(ApiException):
    def __init__(self, retry_after: int = 60, detail: str = "Rate limit exceeded", instance: Optional[str] = None):
        super().__init__(
            status=429,
            title="Too Many Requests",
            detail=detail,
            instance=instance,
            headers={"Retry-After": str(retry_after)},
        )


class BadRequestException(ApiException):
    def __init__(self, detail: str = "Invalid request", instance: Optional[str] = None, invalid_params: Optional[List[Dict[str, Any]]] = None):
        super().__init__(status=400, title="Bad Request", detail=detail, instance=instance, invalid_params=invalid_params)


class CircuitBreakerOpenException(ApiException):
    def __init__(self, detail: str = "Service temporarily unavailable due to downstream protection", instance: Optional[str] = None):
        super().__init__(
            status=503,
            title="Service Unavailable",
            detail=detail,
            instance=instance,
            headers={"Retry-After": "10"},
        )
